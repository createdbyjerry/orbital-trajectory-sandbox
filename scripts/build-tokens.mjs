#!/usr/bin/env node
/**
 * build-tokens.mjs
 * Converts tokens/tokens.json (W3C DTCG-style) into assets/css/tokens.css.
 * Zero dependencies — runs on any Node >= 18.
 *
 *   node scripts/build-tokens.mjs           Build tokens.css
 *   node scripts/build-tokens.mjs --check   Exit 1 if tokens.css is out of date (for CI)
 *
 * Rules
 *   - Any object with a "$value" is a token. Everything else is a group.
 *   - "$type" is inherited from the nearest parent group.
 *   - CSS variable name = path joined with "-":  color.accent -> --color-accent
 *   - References like "{color.white}" become var(--color-white), so themes
 *     can override a base token and everything that references it follows.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT  = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC   = resolve(ROOT, 'tokens/tokens.json');
const OUT   = resolve(ROOT, 'assets/css/tokens.css');
const CHECK = process.argv.includes('--check');

const REF = /\{([^}]+)\}/g;
const NAME_OK = /^[a-z0-9-]+$/i;
const GENERIC_FONTS = new Set([
  'serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui',
  'ui-serif', 'ui-sans-serif', 'ui-monospace', 'ui-rounded', 'emoji', 'math',
]);

/* ---------- 1. flatten the tree into a token list ---------- */
function flatten(node, path = [], inheritedType, out = []) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const p = [...path, key];
    if (child === null || typeof child !== 'object' || Array.isArray(child)) {
      throw new Error(`"${p.join('.')}" must be a group or a token object with "$value".`);
    }
    if (!NAME_OK.test(key)) {
      throw new Error(`"${p.join('.')}": key "${key}" may only contain letters, digits and "-".`);
    }
    const type = child.$type ?? inheritedType;
    if ('$value' in child) {
      out.push({ path: p, id: p.join('.'), cssVar: `--${p.join('-')}`, type, value: child.$value });
    } else {
      flatten(child, p, type, out);
    }
  }
  return out;
}

/* ---------- 2. validate references (existence + cycles) ---------- */
function refsOf(value) {
  if (typeof value === 'string') return [...value.matchAll(REF)].map(m => m[1]);
  if (value && typeof value === 'object') return Object.values(value).flatMap(refsOf);
  return [];
}

function validateRefs(tokens) {
  const byId = new Map(tokens.map(t => [t.id, t]));
  const state = new Map(); // id -> 'visiting' | 'done'
  const visit = (id, chain) => {
    if (state.get(id) === 'done') return;
    if (state.get(id) === 'visiting') {
      throw new Error(`Circular reference: ${[...chain, id].join(' -> ')}`);
    }
    state.set(id, 'visiting');
    for (const ref of refsOf(byId.get(id).value)) {
      if (!byId.has(ref)) throw new Error(`"${id}" references unknown token {${ref}}.`);
      visit(ref, [...chain, id]);
    }
    state.set(id, 'done');
  };
  tokens.forEach(t => visit(t.id, []));
}

/* ---------- 3. format values as CSS ---------- */
const toVar = str => String(str).replace(REF, (_, ref) => `var(--${ref.split('.').join('-')})`);

function dimension(v) {
  // supports "12px" or the newer DTCG object form { value: 12, unit: "px" }
  if (v && typeof v === 'object' && 'value' in v) return `${v.value}${v.unit ?? ''}`;
  return toVar(v);
}

function fontFamily(v) {
  if (!Array.isArray(v)) return toVar(v);
  return v.map(f => (GENERIC_FONTS.has(f) || !/\s/.test(f) || f.startsWith('{') ? toVar(f) : `'${f}'`)).join(', ');
}

function shadow(v) {
  if (typeof v === 'string') return toVar(v);
  const list = Array.isArray(v) ? v : [v];
  return list.map(s => {
    const parts = [dimension(s.offsetX ?? '0'), dimension(s.offsetY ?? '0'), dimension(s.blur ?? '0')];
    const spread = s.spread === undefined ? '0' : dimension(s.spread);
    if (spread !== '0' && spread !== '0px') parts.push(spread);
    parts.push(toVar(s.color));
    if (s.inset) parts.unshift('inset');
    return parts.join(' ');
  }).join(', ');
}

function formatValue(t) {
  const v = t.value;
  switch (t.type) {
    case 'fontFamily': return fontFamily(v);
    case 'shadow':     return shadow(v);
    case 'dimension':
    case 'duration':   return dimension(v);
    default:
      if (typeof v === 'number') return String(v);
      if (typeof v === 'string') return toVar(v);
      throw new Error(`"${t.id}": don't know how to format ${JSON.stringify(v)} (type: ${t.type ?? 'none'}).`);
  }
}

/* ---------- 4. render ---------- */
function render(tokens) {
  const lines = [
    '/**',
    ' * AUTO-GENERATED by scripts/build-tokens.mjs — DO NOT EDIT BY HAND.',
    ' * Source: tokens/tokens.json  ·  Rebuild: npm run tokens:build',
    ' */',
    ':root{',
  ];
  let group = null;
  for (const t of tokens) {
    if (t.path[0] !== group) {
      group = t.path[0];
      if (lines.at(-1) !== ':root{') lines.push('');
      lines.push(`  /* ===== ${group.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase())} ===== */`);
    }
    lines.push(`  ${t.cssVar}:${formatValue(t)};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

/* ---------- run ---------- */
try {
  const json = JSON.parse(await readFile(SRC, 'utf8'));
  const tokens = flatten(json);

  const dupes = tokens.map(t => t.cssVar).filter((n, i, a) => a.indexOf(n) !== i);
  if (dupes.length) throw new Error(`Duplicate CSS variable names: ${[...new Set(dupes)].join(', ')}`);

  validateRefs(tokens);
  const css = render(tokens);
  const rel = relative(ROOT, OUT);

  if (CHECK) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== css) {
      console.error(`✖ ${rel} is out of date. Run "npm run tokens:build" and commit the result.`);
      process.exit(1);
    }
    console.log(`✔ ${rel} is up to date (${tokens.length} tokens).`);
  } else {
    await mkdir(dirname(OUT), { recursive: true });
    await writeFile(OUT, css);
    console.log(`✔ Wrote ${tokens.length} tokens to ${rel}`);
  }
} catch (err) {
  console.error(`✖ Token build failed: ${err.message}`);
  process.exit(1);
}
